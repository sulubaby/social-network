INSERT INTO post_reactions (post_id, user_id, value)
SELECT p.id, u.id, 1
FROM posts p
CROSS JOIN user u
WHERE u.id != p.user_id
  AND abs(random()) % 100 < 20
  AND NOT EXISTS (
      SELECT 1 FROM post_reactions pr
      WHERE pr.post_id = p.id AND pr.user_id = u.id
  );

